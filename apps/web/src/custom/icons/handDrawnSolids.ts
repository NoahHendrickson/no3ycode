type Element = IconSvgElement[number];
type Extra = Record<string, string | number>;

/** The gap left round a part that sits in front of another. */
const GAP = 1.25;

const body = (key: string, d: string, extra: Extra = {}) =>
  filledBody(["path", { d, ...extra, key }]);
const cut = (key: string, d: string, width: number, extra: Extra = {}) =>
  knockout(["path", { d, ...extra, key }], width);
/** Cuts a gap round `front` (or along `edge` only), then restores `front`, so only what lies
 * behind it is cut. */
const around = (front: Element, gap = GAP, edge?: string): Element[] => {
  const [tag, attrs] = front;
  const key = String(attrs["key"]);
  return [
    edge
      ? cut(`${key}-gap`, edge, 2 * gap)
      : knockout([tag, { ...attrs, key: `${key}-gap` }], 2 * gap),
    [tag, { ...attrs, fill: "white", stroke: "none", key: `${key}-front` }],
  ];
};
const solid = (bodies: Element[], knockouts: Element[]): GlyphDrawing => ({
  bodies,
  knockouts,
  holes: [],
  plain: [],
});

